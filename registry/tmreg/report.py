"""Row selection and md/csv/html rendering. Pure functions: no import of core, no I/O."""
from __future__ import annotations

import csv
import html
import io
import re
from dataclasses import dataclass

from .model import LABELS, RISK_FIELDS, SNAPSHOT_FIELDS

MARKERS = ("", "re-review pending", "PENDING", "REJECTED", "RETIRED")
GENERATED = "<!-- Generated by tmreg. Do not edit; regenerate with ./tmreg report <slug>. -->"
INCOMPLETE = "> Detail incomplete: imported from the reference catalog as a one-liner."


def _sort_key(risk_id) -> tuple[int, int]:
    m = re.fullmatch(r"(PT|T)-(\d+)", risk_id) if isinstance(risk_id, str) else None
    return (2, 0) if m is None else (0 if m.group(1) == "T" else 1, int(m.group(2)))


@dataclass(frozen=True)
class ReportRow:
    risk: dict
    marker: str


def select(risks, *, include_pending=False, include_retired=False,
           include_rejected=False) -> list[ReportRow]:
    out: list[tuple[tuple, ReportRow]] = []
    for r in risks:
        key = _sort_key(r["id"])
        state = r["review_state"]
        if state == "rejected":
            if include_rejected:
                out.append(((key, 0), ReportRow(r, "REJECTED")))
        elif state == "pending":
            snap = r.get("last_approved")
            if snap is not None:
                shown = {**r, **{f: snap[f] for f in SNAPSHOT_FIELDS}}
                out.append(((key, 0), ReportRow(shown, "re-review pending")))
                if include_pending:
                    out.append(((key, 1), ReportRow(r, "PENDING")))
            elif include_pending:
                out.append(((key, 1), ReportRow(r, "PENDING")))
        elif r.get("status") == "retired":
            if include_retired:
                out.append(((key, 0), ReportRow(r, "RETIRED")))
        else:
            out.append(((key, 0), ReportRow(r, "")))
    return [row for _, row in sorted(out, key=lambda t: t[0])]


def _join(value, sep: str) -> str:
    if value is None:
        return ""
    if isinstance(value, (list, tuple)):
        return sep.join(str(v) for v in value)
    return str(value)


def cell(value) -> str:
    return (_join(value, "; ").replace("|", "\\|").replace("\r\n", "<br>").replace("\n", "<br>"))


def _score(r) -> str:
    return "" if r.get("score") in (None, "") else f"{r['score']} ({r.get('score_method') or ''})"


def _origin(r) -> str:
    return f"{r.get('origin') or ''} ({r.get('origin_ref') or ''})"


def _status(row: ReportRow) -> str:
    s = row.risk.get("status") or ""
    return f"{s} ({row.marker})" if row.marker else s


def _date(r) -> str:
    return (r.get("updated_at") or "")[:10]


# (label, key); keys not in a risk row are computed in _register_cells.
REGISTER_COLUMNS = [
    ("ID", "id"), ("Element(s)", "elements"), ("Category", "category"), ("Threat", "title"),
    ("Attack path", "attack_path"), ("Likelihood", "likelihood"), ("Impact", "impact_rating"),
    ("Score (method)", "score"), ("Treatment", "treatment"),
    ("Recommended controls", "recommended_controls"),
    ("Implemented controls", "implemented_controls"), ("Control refs", "control_refs"),
    ("Exception ref", "exception_ref"), ("Owner", "owner"), ("Status", "status"),
    ("Origin", "origin"), ("Drafted by", "drafted_by"), ("Test", "test"), ("Ticket", "ticket"),
    ("Date", "updated_at"), ("Notes", "notes"),
]


def _register_cells(row: ReportRow) -> list[str]:
    r = row.risk
    special = {"score": _score(r), "status": _status(row), "origin": _origin(r),
               "updated_at": _date(r)}
    return [special[k] if k in special else _join(r.get(k), "; ") for _, k in REGISTER_COLUMNS]


CSV_HEADER = (
    "id,elements,category,threat,attack_path,likelihood,impact,score,score_method,treatment,"
    "recommended_controls,implemented_controls,control_refs,exception_ref,owner,status,origin,"
    "origin_ref,drafted_by,test_ref,ticket,date,notes,"
    "description,attack_scenario,impact_detail,likelihood_rationale,assumptions,evidence,"
    "decision_requested,ai_confidence,review_state,reviewed_by,reviewed_at,review_note"
).split(",")

_CSV_SOURCE = {"threat": "title", "impact": "impact_rating", "test_ref": "test",
               "date": "updated_at", "impact_detail": "impact"}


def _csv_cells(row: ReportRow) -> list[str]:
    r = row.risk
    out = []
    for col in CSV_HEADER:
        v = r.get(_CSV_SOURCE.get(col, col))
        out.append(_date(r) if col == "date" else _join(v, ";"))
    return out


def render_csv(rows) -> str:
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(CSV_HEADER)
    for row in rows:
        w.writerow(_csv_cells(row))
    return buf.getvalue()


_DETAIL_FIELDS = [f for f in RISK_FIELDS if f not in ("id", "title", "last_approved")]


def _detail(row: ReportRow) -> list[tuple[str, str]]:
    out = []
    for f in _DETAIL_FIELDS:
        v = row.risk.get(f)
        s = _join(v, "; ")
        out.append((LABELS[f], s if s != "" else "—"))
    return out


def _heading(row: ReportRow) -> str:
    r = row.risk
    return f"{r['id']}: {r.get('title') or ''}" + (f" ({row.marker})" if row.marker else "")


def _incomplete(row: ReportRow) -> bool:
    return row.risk.get("detail_complete") == 0


def render_md(rows, *, title, stamp, scope_note) -> str:
    lines = [GENERATED, "", f"# Threat register: {title}", "", f"As of {stamp}. {scope_note}", "",
             "| " + " | ".join(l for l, _ in REGISTER_COLUMNS) + " |",
             "|" + "---|" * len(REGISTER_COLUMNS)]
    for row in rows:
        lines.append("| " + " | ".join(cell(c) for c in _register_cells(row)) + " |")
    lines += ["", "## Risk detail", ""]
    for row in rows:
        lines += [f"### {_md_heading(row)}", ""]
        if _incomplete(row):
            lines += [INCOMPLETE, ""]
        lines += ["| Field | Value |", "|---|---|"]
        lines += [f"| {cell(k)} | {cell(v)} |" for k, v in _detail(row)]
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def _md_heading(row: ReportRow) -> str:
    # headings are one line; keep values from adding structure
    return _heading(row).replace("\r", " ").replace("\n", " ")


_CSS = """body{font:14px/1.45 system-ui,sans-serif;margin:1.5rem;color:#1a1a1a;background:#fff}
table{border-collapse:collapse;margin:.5rem 0 1.5rem}
th,td{border:1px solid #c8c8c8;padding:.25rem .5rem;text-align:left;vertical-align:top}
th{background:#f0f0f0}
.note{border-left:4px solid #b58900;padding-left:.75rem}
@media (prefers-color-scheme: dark){
body{color:#e6e6e6;background:#161616}
th,td{border-color:#444}th{background:#262626}}"""


def _h(value) -> str:
    return html.escape(_join(value, "; "), quote=True).replace("\r\n", "<br>").replace("\n", "<br>")


def render_html(rows, *, title, stamp, scope_note) -> str:
    out = ["<!DOCTYPE html>", '<html lang="en">', "<head>", '<meta charset="utf-8">',
           '<meta name="viewport" content="width=device-width, initial-scale=1">',
           f"<title>Threat register: {_h(title)}</title>", f"<style>{_CSS}</style>", "</head>",
           "<body>", f"<h1>Threat register: {_h(title)}</h1>",
           f"<p>As of {_h(stamp)}. {_h(scope_note)}</p>", "<table>", "<thead><tr>"
           + "".join(f"<th>{_h(l)}</th>" for l, _ in REGISTER_COLUMNS) + "</tr></thead>", "<tbody>"]
    for row in rows:
        out.append("<tr>" + "".join(f"<td>{_h(c)}</td>" for c in _register_cells(row)) + "</tr>")
    out += ["</tbody>", "</table>", "<h2>Risk detail</h2>"]
    for row in rows:
        out.append(f"<h3>{_h(_heading(row))}</h3>")
        if _incomplete(row):
            out.append('<p class="note">Detail incomplete: imported from the reference catalog '
                       "as a one-liner.</p>")
        out.append("<table><thead><tr><th>Field</th><th>Value</th></tr></thead><tbody>")
        out += [f"<tr><td>{_h(k)}</td><td>{_h(v)}</td></tr>" for k, v in _detail(row)]
        out.append("</tbody></table>")
    out += ["</body>", "</html>"]
    return "\n".join(out) + "\n"
