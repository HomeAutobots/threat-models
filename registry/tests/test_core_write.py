class EditTest(TmpTestCase):
    def setUp(self):
        super().setUp()
        self.reg = make_registry(self.tmp)
        self.run = start(self.reg)
        self.reg.add_risk("demo", ai_fields(), run_id=self.run)

    def force(self, risk_id, fields):
        """Stand-in for Task 4's review operations: write review fields straight through the ledger."""
        with self.reg.conn:
            ledger.write_row(self.reg.conn, "demo", "risks", risk_id, fields, op="test", actor="human:test")

    def test_edit_pending_stays_pending_and_logs(self):
        reg, run = self.reg, self.run
        with mock.patch("tmreg.db.now", return_value="2026-12-01T00:00:00Z"):
            r = reg.edit_risk("demo", "T-01", {"owner": "A. Okafor"}, run_id=run)
        self.assertEqual((r["review_state"], r["updated_at"], r["model_approval_id"]),
                         ("pending", "2026-12-01T00:00:00Z", "MODEL-1"))
        self.assertIsNone(r["last_approved"])
        last = reg.history("demo", "T-01")[-1]
        self.assertEqual((last["op"], last["actor"], last["diff"]["owner"]), ("edit", f"ai:{run}", [None, "A. Okafor"]))
        with self.assertRaisesRegex(RegistryError, "no changes"):
            reg.edit_risk("demo", "T-01", {"owner": "A. Okafor"}, run_id=run)
        with self.assertRaisesRegex(RegistryError, "no changes"):
            reg.edit_risk("demo", "T-01", {"owner": "  A. Okafor "}, run_id=run)  # same after normalizing

    def test_human_edit_is_attributed_to_reviewer(self):
        with tty():
            self.reg.edit_risk("demo", "T-01", {"status": "planned", "control_refs": "ADR-07; BR-AUTHN-01"}, run_id=None)
        r = self.reg.get_risk("demo", "T-01")
        self.assertEqual((r["status"], r["control_refs"]), ("planned", ["ADR-07", "BR-AUTHN-01"]))
        self.assertEqual(self.reg.history("demo", "T-01")[-1]["actor"], "human:Test Reviewer")

    def test_edit_refusals_write_nothing(self):
        reg, run = self.reg, self.run
        before = len(reg.history("demo"))
        with self.assertRaisesRegex(RegistryError, "no risk T-99 in demo"):
            reg.edit_risk("demo", "T-99", {"owner": "x"}, run_id=run)
        cases = {"retire": {"status": "retired"}, "review_state": {"review_state": "approved"},
                 "nope": {"nope": "x"}, "missing required field\\(s\\): description": {"description": ""},
                 "80": {"attack_scenario": "short"}, "X9": {"elements": ["C2", "X9"]},
                 "STRIDE": {"category": "Linking"}, "status cannot be empty": {"status": ""},
                 "origin": {"origin": "rumor"}, "no changes": {}}
        for msg, fields in cases.items():
            with self.subTest(msg=msg), self.assertRaisesRegex(RegistryError, msg):
                reg.edit_risk("demo", "T-01", fields, run_id=run)
        self.assertEqual(len(reg.history("demo")), before)

    def test_rejected_and_retired_risks_are_not_edited(self):
        reg, run = self.reg, self.run
        reg.add_risk("demo", ai_fields(), run_id=run)  # T-02
        self.force("T-01", {"review_state": "rejected"})
        self.force("T-02", {"status": "retired", "review_state": "approved"})
        with self.assertRaisesRegex(RegistryError, "rejected risks are not edited; add a new risk"):
            reg.edit_risk("demo", "T-01", {"owner": "x"}, run_id=run)
        with self.assertRaisesRegex(RegistryError, "retired"):
            reg.edit_risk("demo", "T-02", {"owner": "x"}, run_id=run)

    def test_edit_of_approved_risk_returns_to_review_with_snapshot(self):
        reg, run = self.reg, self.run
        self.force("T-01", {"review_state": "approved", "reviewed_by": "Test Reviewer",
                            "reviewed_at": "2026-11-07T12:00:00Z", "review_note": NOTE})
        r = reg.edit_risk("demo", "T-01", {"owner": "A"}, run_id=run)
        self.assertEqual((r["review_state"], r["reviewed_by"], r["reviewed_at"], r["review_note"]),
                         ("pending", None, None, None))
        self.assertEqual(set(r["last_approved"]), set(model.SNAPSHOT_FIELDS))
        self.assertEqual((r["last_approved"]["owner"], r["last_approved"]["review_note"]), (None, NOTE))
        r = reg.edit_risk("demo", "T-01", {"owner": "B"}, run_id=run)  # still pending: snapshot kept
        self.assertEqual((r["owner"], r["last_approved"]["owner"]), ("B", None))

    def test_edit_rechecks_elements_against_latest_model(self):  # Review Focus 5, second half
        reg, run = self.reg, self.run
